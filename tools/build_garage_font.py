"""Build the isolated native font atlas with explicit Unicode glyph ordering.

Requires Pillow 13.0.0 and the pinned DejaVu Sans source (see the shipped
font licence). The game uses only the generated XML/DDS, never a system font.
"""
import argparse
import hashlib
import math
import struct
import xml.etree.ElementTree as ET
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

REPO = Path(__file__).resolve().parent.parent
OUTPUT = REPO / 'res/system/fonts/battle_conquest'
SOURCE_SHA256 = 'ae7b7855e115a5966d8b1b3f80f254ccc117ec86f9965e202ee2940453837280'
RANGES = ((0x20, 0x7e), (0xa0, 0x24f), (0x370, 0x52f), (0x2000, 0x206f), (0x20ac, 0x20ac), (0x2264, 0x2265))


def dds(image):
    width, height = image.size
    fields = [124, 0x100f, height, width, width * 4, 0, 0] + [0] * 11
    fields += [32, 0x41, 0, 32, 0xff0000, 0xff00, 0xff, 0xff000000]
    fields += [0x1000, 0, 0, 0, 0]
    return b'DDS ' + struct.pack('<31I', *fields) + image.tobytes('raw', 'BGRA')


def build(source):
    if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise SystemExit('Unexpected font source: use the pinned DejaVu Sans 2.37 file.')
    font = ImageFont.truetype(str(source), 17, layout_engine=ImageFont.Layout.BASIC)
    characters = [chr(code) for first, last in RANGES for code in range(first, last + 1)]
    boxes = [font.getbbox(char, anchor='ls') for char in characters]
    baseline = 1 - min(box[1] for box in boxes)
    height = max(24, baseline + max(box[3] for box in boxes) + 1)
    placements, x, y, row = [], 2, 2, height + 2
    for char, box in zip(characters, boxes):
        left = max(0, -box[0])
        advance = max(1, math.ceil(font.getlength(char)), box[2] + left)
        if x + advance + 2 > 1024:
            x, y = 2, y + row
        placements.append((char, x, y, advance, left))
        x += advance + 2
    atlas_height = 1 << (y + height + 1).bit_length()
    image = Image.new('RGBA', (1024, atlas_height), (255, 255, 255, 0))
    draw = ImageDraw.Draw(image)
    for char, x, y, width, left in placements:
        draw.text((x + left, y + baseline), char, font=font, anchor='ls', fill=(255, 255, 255, 255))
    root = ET.Element('root')
    root.append(ET.Comment('Generated by tools/build_garage_font.py; DejaVu Sans SHA256 ' + SOURCE_SHA256))
    creation = ET.SubElement(root, 'creation')
    for key, value in [('sourceFont', 'DejaVu Sans'), ('sourceFontSize', '-17'),
                       ('effectsMargin', '0'), ('textureMargin', '0'), ('dropShadow', 'false')]:
        ET.SubElement(creation, key).text = value
    # Never use startChar/endChar: those ranges are interpreted through CP_ACP.
    for first, last in RANGES:
        ET.SubElement(creation, 'unicodeRange').text = 'U+%04X-U+%04X' % (first, last)
    generated = ET.SubElement(root, 'generated')
    values = [('map', 'system/fonts/battle_conquest/garage.dds'),
              ('mapDimensions', '1024 %s' % atlas_height), ('height', str(height)),
              ('maxWidth', str(max(place[3] for place in placements))),
              ('uvs', ''.join('%04x%04x' % (x, y - 1) for char, x, y, width, left in placements)),
              ('widths', ''.join('%04x' % width for char, x, y, width, left in placements))]
    for key, value in values:
        ET.SubElement(generated, key).text = value
    ET.indent(root)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(root).write(OUTPUT / 'garage.font', encoding='utf-8', xml_declaration=True)
    (OUTPUT / 'garage.dds').write_bytes(dds(image))
    print('Built %s Unicode glyphs, %sx%s atlas, %spx lines.' % (len(characters), 1024, atlas_height, height))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'))
    build(parser.parse_args().source)
